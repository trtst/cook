export function assertPublicContentUserProfiles(profiles: readonly PublicContentUserProfile[]) {
  if (profiles.length !== 100) {
    throw new Error("公共内容用户资料必须正好包含 100 个用户");
  }
  if (new Set(profiles.map(item => item.uid)).size !== profiles.length) {
    throw new Error("公共内容用户 UID 必须唯一");
  }
  if (new Set(profiles.map(item => item.nickname)).size !== profiles.length) {
    throw new Error("公共内容用户昵称必须唯一");
  }
  if (profiles[0]?.uid !== 10001 || profiles[0].nickname !== "灵感菜谱库") {
    throw new Error("公共内容用户资料必须保留 UID 10001 的灵感菜谱库");
  }
  for (const profile of profiles) {
    if (!/^\p{Script=Han}{2,6}$/u.test(profile.nickname)) {
      throw new Error(`公共内容用户昵称必须为 2 至 6 个中文字符: ${profile.uid}`);
    }
    if (profile.nickname.includes("炊火")) {
      throw new Error(`公共内容用户昵称不能包含炊火: ${profile.uid}`);
    }
  }
}

export function missingPublicContentUserProfiles(existingUsers: readonly { uid: number }[]) {
  assertPublicContentUserProfiles(publicContentUserProfiles);
  const existingUids = new Set(existingUsers.map(item => item.uid));
  return publicContentUserProfiles.filter(item => !existingUids.has(item.uid));
}

export function buildPoolPlan(
  existingUsers: readonly { id: number; uid: number; nickname: string | null }[],
  currentMemberIds: readonly number[]
) {
  assertPublicContentUserProfiles(publicContentUserProfiles);
  const profileByUid = new Map<number, PublicContentUserProfile>(
    publicContentUserProfiles.map(item => [item.uid, item])
  );
  const userByUid = new Map(existingUsers.map(item => [item.uid, item]));
  const desiredUserIds = new Set(
    existingUsers
      .filter(item => profileByUid.has(item.uid))
      .map(item => item.id)
  );

  return {
    createProfiles: publicContentUserProfiles.filter(item => !userByUid.has(item.uid)),
    nicknameUpdates: publicContentUserProfiles.flatMap(profile => {
      const user = userByUid.get(profile.uid);
      return user && user.nickname !== profile.nickname
        ? [{ id: user.id, nickname: profile.nickname }]
        : [];
    }),
    outgoingUserIds: currentMemberIds.filter(userId => !desiredUserIds.has(userId))
  };
}
